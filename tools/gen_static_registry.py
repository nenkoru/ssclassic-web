#!/usr/bin/env python3
"""Generate port/<game>/static_symbols.cpp: a name -> address table that replaces
dlopen()/dlsym() for the modules upstream builds as shared libraries
(Entities, Game, Shaders, vorbisfile).

Every function is declared with its real signature: wasm-ld checks signatures and
an address taken through a mismatched declaration becomes a trapping stub.

Usage: tools/gen_static_registry.py SamTFE|SamTSE   (run after gen_entities.sh)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_list(cmake_text, name):
    m = re.search(r"^set\(%s\n(.*?)^\)" % name, cmake_text, re.M | re.S)
    return m.group(1).split() if m else []


def main():
    game = sys.argv[1]
    src = os.path.join(ROOT, "src", game, "Sources")
    cm = open(os.path.join(ROOT, "port", game, "sources.cmake")).read()

    es = read_list(cm, "ENGINE_ES") + read_list(cm, "GAME_ES")
    files = [f + "_tables.h" for f in es] + [f + ".cpp" for f in es]
    files += read_list(cm, "ENGINE_SRCS") + read_list(cm, "ENTITIES_EXTRA_SRCS") + read_list(cm, "SAFEMATH_SRCS")
    shader_files = read_list(cm, "SHADERS_SRCS")

    classes, shaders, descs = set(), set(), set()
    for f in files:
        p = os.path.join(src, f)
        if not os.path.exists(p):
            continue
        t = open(p, errors="replace").read()
        classes |= set(re.findall(r"ENTITY_CLASSDEFINITION(?:_BASE)?\(\s*(\w+)\s*,", t))
    for f in shader_files:
        t = open(os.path.join(src, f), errors="replace").read()
        shaders |= set(re.findall(r"^\s*SHADER_MAIN\(\s*(\w+)\s*\)", t, re.M))
        descs |= set(re.findall(r"^\s*SHADER_DESC\(\s*(\w+)\s*,", t, re.M))

    ovh = open(os.path.join(src, "Engine/Sound/ov_functions.h")).read()
    ov = sorted(set(re.findall(r"DLLFUNCTION\(\s*OVF\s*,[^,]*,\s*(\w+)", ovh)))

    out = []
    w = out.append
    w(f"// Generated by tools/gen_static_registry.py for {game}. Do not edit.")
    w("#include <string.h>")
    w("#include <vorbis/vorbisfile.h>")
    w("struct CDLLEntityClass; struct ShaderDesc; class CGame;")
    w('extern "C" {')
    w("CGame *GAME_Create(void);  // extern \"C\" in GameMP")
    for c in sorted(classes):
        w(f"extern CDLLEntityClass {c}_DLLClass;")
    for s in sorted(shaders):
        w(f"void Shader_{s}(void);")
    for s in sorted(descs):
        w(f"void Shader_Desc_{s}(ShaderDesc &);")
    w("}")
    w("struct SE1StaticSymbol { const char *name; void *addr; };")
    w("static const SE1StaticSymbol _aSymbols[] = {")
    for c in sorted(classes):
        w(f'  {{"{c}_DLLClass", (void *)&{c}_DLLClass}},')
    for s in sorted(shaders):
        w(f'  {{"Shader_{s}", (void *)&Shader_{s}}},')
    for s in sorted(descs):
        w(f'  {{"Shader_Desc_{s}", (void *)&Shader_Desc_{s}}},')
    w('  {"GAME_Create", (void *)&GAME_Create},')
    for f in ov:
        w(f'  {{"{f}", (void *)&{f}}},')
    w("};")
    w('extern "C" void *SE1_FindStaticSymbol(const char *name) {')
    w("  for (unsigned i = 0; i < sizeof(_aSymbols) / sizeof(_aSymbols[0]); i++)")
    w("    if (strcmp(_aSymbols[i].name, name) == 0) return _aSymbols[i].addr;")
    w("  return 0;")
    w("}")

    path = os.path.join(ROOT, "port", game, "static_symbols.cpp")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"{game}: {len(classes)} entity classes, {len(shaders)} shaders, {len(descs)} shader descs, {len(ov)} vorbis fns")


if __name__ == "__main__":
    main()
