#!/usr/bin/env python3
"""Extract source lists from the upstream SamTFE/SamTSE CMakeLists.txt into
port/<game>/sources.cmake, so our wasm build stays in sync with upstream
without patching its 1700-line CMake file.

Usage: tools/extract_sources.py SamTFE|SamTSE
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def block_after(text, anchor, start=0):
    """Return whitespace-separated tokens between `anchor` and the matching ')'."""
    i = text.index(anchor, start) + len(anchor)
    depth = 1
    j = i
    while depth:
        c = text[j]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        j += 1
    body = text[i : j - 1]
    toks = []
    for line in body.splitlines():
        line = line.split("#", 1)[0].strip()
        toks += line.split()
    return toks, j


def files_only(toks, srcdir):
    out = []
    for t in toks:
        if t.startswith("${") or t in ("SHARED", "STATIC"):
            continue
        if not t.endswith((".cpp", ".c")):
            continue
        if not os.path.exists(os.path.join(srcdir, t)):
            print(f"  warn: missing {t}", file=sys.stderr)
            continue
        out.append(t)
    return out


def main():
    game = sys.argv[1]
    srcdir = os.path.join(ROOT, "src", game, "Sources")
    text = open(os.path.join(srcdir, "CMakeLists.txt")).read()

    entities = re.findall(r"^\s*entity\(([^)]+)\)", text, re.M)
    entities = [e for e in entities if os.path.exists(os.path.join(srcdir, e + ".es"))]
    engine_es = [e for e in entities if e.startswith("Engine/")]
    game_es = [e for e in entities if not e.startswith("Engine/")]
    ents_dir = "Entities" if game == "SamTFE" else "EntitiesMP"
    game_es = [e for e in game_es if e.startswith(ents_dir + "/")]

    # Entities library: the add_library variant whose Common files live in ents_dir.
    pos = 0
    ent_extra = []
    while True:
        try:
            toks, pos = block_after(text, "add_library(${ENTITIESMPLIB} SHARED", pos)
        except ValueError:
            break
        f = files_only(toks, srcdir)
        if f and f[0].startswith(ents_dir + "/"):
            ent_extra = f
            break

    game_srcs = files_only(block_after(text, "add_library(${GAMEMPLIB} SHARED")[0], srcdir)
    shader_srcs = files_only(block_after(text, "add_library(${SHADERSLIB} SHARED")[0], srcdir)
    safemath = files_only(block_after(text, "set(ENGINE_SAFEMATH_SRCS")[0], srcdir)
    # Second set(ENGINE_SRCS ...) is the non-Vulkan variant.
    first = text.index("set(ENGINE_SRCS")
    engine = files_only(block_after(text, "set(ENGINE_SRCS", first + 1)[0], srcdir)
    sam = files_only(block_after(text, "add_executable(SeriousSam${MP}")[0], srcdir)
    amp = files_only(block_after(text, "set(AMP11LIB_SOURCE_FILES")[0], srcdir)
    zlib = files_only(block_after(text, "set(ZLIB_SRCS\n")[0], srcdir) if "set(ZLIB_SRCS\n" in text else []

    lists = {
        "ENGINE_ES": engine_es,
        "GAME_ES": game_es,
        "ENTITIES_EXTRA_SRCS": ent_extra,
        "GAME_SRCS": game_srcs,
        "SHADERS_SRCS": shader_srcs,
        "SAFEMATH_SRCS": safemath,
        "ENGINE_SRCS": engine,
        "SAM_SRCS": sam,
        "AMP11_SRCS": amp,
        "ZLIB_SRCS": zlib,
    }
    outdir = os.path.join(ROOT, "port", game)
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "sources.cmake"), "w") as f:
        f.write(f"# Generated by tools/extract_sources.py from src/{game}/Sources/CMakeLists.txt. Do not edit.\n")
        f.write(f'set(ENTITIES_DIR "{ents_dir}")\n')
        for k, v in lists.items():
            f.write(f"set({k}\n")
            for x in v:
                f.write(f"    {x}\n")
            f.write(")\n")
    for k, v in lists.items():
        print(f"{game} {k}: {len(v)}")


if __name__ == "__main__":
    main()
