from dataclasses import dataclass
from typing import Any, Dict, List

from BaseClasses import Item, ItemClassification, Location, MultiWorld, Region
from Options import DeathLink, PerGameCommonOptions
from worlds.AutoWorld import WebWorld, World

from . import data

_CLASSIFICATION = {
    "progression": ItemClassification.progression,
    "useful": ItemClassification.useful,
    "filler": ItemClassification.filler,
}


class SeriousSamTFEItem(Item):
    game = data.GAME


class SeriousSamTFELocation(Location):
    game = data.GAME


class SeriousSamTFEWeb(WebWorld):
    """Serious Sam: The First Encounter (Serious Engine 1) as an Archipelago game.
    Weapons and pickups from the levels, generated by this world package."""
    theme = "stone"


@dataclass
class SeriousSamTFEOptions(PerGameCommonOptions):
    death_link: DeathLink


class SeriousSamTFEWorld(World):
    game = data.GAME
    web = SeriousSamTFEWeb()
    options_dataclass = SeriousSamTFEOptions
    options: SeriousSamTFEOptions
    topology_present = False
    required_client_version = (0, 6, 0)

    item_name_to_id = {it["name"]: it["id"] for it in data.ITEMS}
    location_name_to_id = {loc["name"]: loc["id"] for loc in data.LOCATIONS}

    def __init__(self, multiworld: MultiWorld, player: int):
        super().__init__(multiworld, player)
        # One region per distinct level, in first-seen order of the toml.
        self._regions: List[str] = []
        for loc in data.LOCATIONS:
            region = loc["name"].split(": ", 1)[0]
            if region not in self._regions:
                self._regions.append(region)

    def create_regions(self) -> None:
        for name in ["Menu"] + self._regions:
            self.multiworld.regions.append(Region(name, self.player, self.multiworld))

        # Menu -> first level -> ... -> last level.
        prev = self.multiworld.get_region("Menu", self.player)
        for name in self._regions:
            region = self.multiworld.get_region(name, self.player)
            prev.connect(region, f"{name} Entrance")
            prev = region

        for loc in data.LOCATIONS:
            region = self.multiworld.get_region(loc["name"].split(": ", 1)[0], self.player)
            location = SeriousSamTFELocation(self.player, loc["name"], loc["id"], region)
            region.locations.append(location)

        # Event: clearing the last level wins the game.
        last = self.multiworld.get_region(self._regions[-1], self.player)
        event_location = SeriousSamTFELocation(self.player, f"{self._regions[-1]}: Level Complete", None, last)
        last.locations.append(event_location)
        event_location.place_locked_item(SeriousSamTFEItem("Victory", ItemClassification.progression, None, self.player))

    def set_rules(self) -> None:
        # Weapon/key gates (e.g. a location requiring the Rocket Launcher) go here.
        self.multiworld.completion_condition[self.player] = \
            lambda state: state.has("Victory", self.player)

    def create_item(self, name: str) -> SeriousSamTFEItem:
        for it in data.ITEMS:
            if it["name"] == name:
                return SeriousSamTFEItem(name, _CLASSIFICATION[it["classification"]], it["id"], self.player)
        # e.g. the "Victory" event item.
        return SeriousSamTFEItem(name, ItemClassification.filler, None, self.player)

    def get_filler_item_name(self) -> str:
        for it in data.ITEMS:
            if it["classification"] == "filler":
                return it["name"]
        for it in reversed(data.ITEMS):
            if it["classification"] == "useful":
                return it["name"]
        raise ValueError(f"no filler-eligible item in {data.GAME} item table")

    def create_items(self) -> None:
        count = len(data.LOCATIONS)
        names = [it["name"] for it in data.ITEMS][:count]
        names += [self.get_filler_item_name()] * (count - len(names))
        self.multiworld.itempool += [self.create_item(name) for name in names]

    def fill_slot_data(self) -> Dict[str, Any]:
        return {"version": 1}
